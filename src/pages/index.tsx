import type { GetServerSideProps, NextPage } from "next";
import Head from "next/head";
import { SSRProps } from "../util/next_fetch_returns";
import { user } from "../types";
import { getUser } from "../util/functions";
import Navbar from "../components/Navbar";
import Image, { ImageLoader } from 'next/image'


export const getServerSideProps: GetServerSideProps = async (ctx) => {
  const user = await getUser(ctx)
  return SSRProps({user})
}

  
interface IIndexProps {
  user: user
}

const Home: NextPage<IIndexProps> = ({user}) => {
  console.log(user)
  console.log(user?.profileImg)

  const imgLoader: ImageLoader = ({ src }) => {
    return `/api/files/profile_img/${src}`
  }
  
  return (
    <>
      <Head>
        <title>Create Next App</title>
        <meta name="description" content="Generated by create next app" />
        <link rel="icon" href="/favicon.ico" />
      </Head>
      <Navbar user={user}/>
      <Image loader={imgLoader} src={user?.profileImg || 'w'} height="50px" alt="asd" width="56px" />
      <div>
        <h1>{user ? 'Hello ' + user.username : 'Hello world'}</h1>
      </div>
    </>
  );
};

export default Home;
